 on T.CNUMERO=D.ID AND T.CCODARTIC=D.PART_ID AND D.NUMBER_LIQ="'+@POLIMP+'"     
')      
/* Fin */      
exec('set quoted_identifier off      
 select       
 HCNUMIMPOR,HCNUMLIQUI,HCTIPO,HCITEM,HCCODARTIC,HCDESARTIC,HCCANTIDAD,      
