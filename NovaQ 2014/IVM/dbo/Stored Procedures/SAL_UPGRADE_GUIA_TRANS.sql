@RUC VARCHAR(11),@RAZONSOCIAL VARCHAR(100),@DIRECCION  VARCHAR(100),@FORMA_PAG  VARCHAR(2),@MONTO VARCHAR(15),
@MONEDA VARCHAR(2),@TIPO_CAMBIO VARCHAR(15),@USER VARCHAR(8),@TD_REF VARCHAR(2),@NUM_REF VARCHAR(10),
