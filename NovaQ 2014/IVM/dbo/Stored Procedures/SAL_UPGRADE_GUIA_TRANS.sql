DECLARE @ERROR1 INT
DECLARE @ERROR2 INT
DECLARE @ERROR3 INT
DECLARE @TABLA_det VARCHAR(50)
SET @ERROR1=0
SET @ERROR2=0
SET @ERROR3=0
SET @CANT_ERROR=0
set @TABLA_det='tempdb.dbo.'+@IDE+'FACWORDET'

BEGIN TRAN UPDATE_GUIA_TRANS
EXEC('set quoted_identifier off Insert Into WAREHOUSE_TRANS (WAREHOUSE_ID,DOCUMENT_ID,NUMBER_DOCUMENT,TRANS_ID,
TYPE_TRANS,TYPE_GUIA, STATUS_GUIA,DATE_DOCUMENT,SALES_ID,CUSTOMER_ID,VAT_REGISTRATION,CUSTOMER_NAME,ADDR_DLV,
SALES_TERM,AMOUNT,CURRENCY_TYPE,CURRENCY_EXCHANGE,USER_ID,DOC_ID_REF,NUM_ID_REF,DISCOUNT_PER_CUST,DISCOUNT_PER_SP,
UPDATE_DATE,HOUR,RECEIVABLE_GUIA,CARRIER_ID,NUMBER_PURCHASE,NUMBER_ESTIMATING, NUMBER_ORDER, COMMENT)
VALUES("'+@ALMA+'","GS","'+@SER_GUIA+@NUM_GUIA+'","GF","S","GF","F",'+@FECHA+',"'+@VENDEDOR+'","'+@COD_CLI+'","'+@RUC+'",
"'+@RAZONSOCIAL+'","'+@DIRECCION+'","'+@FORMA_PAG+'","'+@MONTO+'","'+@MONEDA+'","'+@TIPO_CAMBIO+'","'+@USER+'",
"'+@TD_REF+'","'+@NUM_REF+'","'+@DESC_CLI+'","'+@DESC_ESP+'",getdate(),"'+@HORA+'","N","'+@TRANS+'","'+@ORDEN_COMPRA+'",
"'+@COTIZA+'","'+@PEDIDO+'","'+@GLOSA+'")')
SET @ERROR1=@@ERROR

IF @FLAG_REF=1
	BEGIN
	EXEC('set quoted_identifier off INSERT INTO WAREHOUSE_TRANS_LINE (WAREHOUSE_ID,DOCUMENT_ID,NUMBER_DOCUMENT,TRANS_ID,ITEM,PART_ID,
	PART_DESCRIPTION,AMOUNT_SALES,AVERAGE_COST,QTY,DISCOUNT_CUST,DISCOUNT_SP,DISCOUNT_PERCENT,DISCOUNT,STATUS,
	AMOUNT_TAX,TAX_PERCENT,AMOUNT_US,AMOUNT,NUMBER_SERIE,NUMBER_LOT,TEXT_COMMENT,CURRENCY_ID,TYPE_EXCHANGE,UNIT_PART
	QTY_REF,REFERENCE,UNIT_REFERENCE,QTY_REFERENCE)SELECT "'+@ALMA+'","GS","'+@SER_GUIA+@NUM_GUIA+'","GV",DFSECUEN,DFCODIGO,
	(CASE WHEN DFCODIGO="TEXTO" THEN DFTEXTO ELSE DFDESCRI END),DFPREC_ORI,DFPREC_VEN,DFCANTID,DFDESCLI,DFDESESP,
	DFPORDES,DFDESCTO,"S",DFIGV,DFIGVPOR,DFIMPUS,DFIMPMN,DFSERIE,DFLOTE,DFTR,"'+@MONEDA+'","'+@TIPO_CAMBIO+'",DFUNIDAD,DFCANTID,
	DFPRESU,REFERENCE,CANTREFERENCIA FROM '+@TABLA_det+'')
	SET @ERROR2=@@ERROR
	END
ELSE
	BEGIN
	EXEC('set quoted_identifier off INSERT INTO WAREHOUSE_TRANS_LINE (WAREHOUSE_ID,DOCUMENT_ID,NUMBER_DOCUMENT,TRANS_ID,ITEM,PART_ID,
	PART_DESCRIPTION,AMOUNT_SALES,AVERAGE_COST,QTY,DISCOUNT_CUST,DISCOUNT_SP,DISCOUNT_PERCENT,DISCOUNT,STATUS,
	AMOUNT_TAX,TAX_PERCENT,AMOUNT_US,AMOUNT,NUMBER_SERIE,NUMBER_LOT,TEXT_COMMENT,CURRENCY_ID,TYPE_EXCHANGE,UNIT_PART,
	QTY_REF,REFERENCE)SELECT "'+@ALMA+'","GS","'+@SER_GUIA+@NUM_GUIA+'","GV",DFSECUEN,DFCODIGO,
	(CASE WHEN DFCODIGO="TEXTO" THEN DFTEXTO ELSE DFDESCRI END),DFPREC_ORI,DFPREC_VEN,DFCANTID,DFDESCLI,DFDESESP,
	DFPORDES,DFDESCTO,"S",DFIGV,DFIGVPOR,DFIMPUS,DFIMPMN,DFSERIE,DFLOTE,DFTR,"'+@MONEDA+'","'+@TIPO_CAMBIO+'",DFUNIDAD,DFCANTID,
	DFPRESU FROM '+@TABLA_det+'')
	SET @ERROR2=@@ERROR
	END

EXEC('set quoted_identifier off Update RECEIVABLE Set DOCUMENT_REF = "GS",SERIE_REF = "'+@SER_GUIA+'",NUMBER_REF = "'+@NUM_GUIA+'",LIST_GUIA = "'+@SER_GUIA+@NUM_GUIA+'" Where DOCUMENT_ID = "'+@TIPO+'" and NUMBER_SERIE = "'+@SERIE+'" and NUMBER_DOCUMENT = "'+@NUMERO+'"')

SET @ERROR3=@@ERROR

IF (@ERROR1<>0 OR @ERROR2<>0 OR @ERROR3<>0)
	BEGIN
		SET @CANT_ERROR=1
		ROLLBACK TRAN UPDATE_GUIA_TRANS
	END
ELSE
	BEGIN
		COMMIT TRAN UPDATE_GUIA_TRANS
	END

