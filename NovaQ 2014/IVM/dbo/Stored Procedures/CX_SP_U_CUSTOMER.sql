


CREATE PROC CX_SP_U_CUSTOMER
@P_ID VARCHAR(20),
@P_NAME VARCHAR(150),
@P_ADDR VARCHAR(100),
@P_PHONE VARCHAR(30),
@P_VAT_REGISTRATION VARCHAR(11),
@P_NUMBER_DOC VARCHAR(11),
@P_DISCOUNT_PERCENT FLOAT,
@P_TERMS_TYPE VARCHAR(4),
@P_STATUS VARCHAR(1),
@P_OPEN_DATE SMALLDATETIME,
@P_CONTACT VARCHAR(200),
@P_STATE_ID VARCHAR(8),
@P_CREATE_USER VARCHAR(8),
@P_CREATE_DATE SMALLDATETIME,
@P_MODIFY_DATE SMALLDATETIME,
@P_TYPE_PRICE VARCHAR(2),
@P_SALES_ID VARCHAR(2),
@P_SELL_ZONE VARCHAR(8),
@P_COUNTRY VARCHAR(30),
@P_DEPARTMENT VARCHAR(30),
@P_PROVINCE VARCHAR(30),
@P_ADDR_DLV VARCHAR(100),
@P_CURRENCY_CREDIT_LIMIT VARCHAR(2),
@P_CREDIT_LIMIT_US FLOAT ,
@P_CREDIT_LIMIT FLOAT,
@P_BALANCE FLOAT,
@P_BALANCE_US FLOAT,
@P_OBSERV VARCHAR(30),
@P_TOTAL_LETTER FLOAT,
@P_TOTAL_RECEIVABLE FLOAT,
@P_TOTAL_CHECK FLOAT,
@P_TOTAL_LETTER_PROTESTED FLOAT,
@P_CUSTOMER_TYPE VARCHAR(2),
@P_BUSINESS_TYPE VARCHAR(2),
@P_TERRITORY VARCHAR(2),
@P_ROUTE VARCHAR(2),
@P_SEGMENT VARCHAR(3),
@P_SEGMENT_LOCATION VARCHAR(3),
@P_BANK_ID VARCHAR(3),
@P_ACCOUNT_NO VARCHAR(12),
@P_DATE_REVIEW VARCHAR(8),
@P_HOUR_VISIT VARCHAR(20),
@P_ATTENTION_TYPE VARCHAR(2),
@P_FAX_NUMBER VARCHAR(15),
@P_EMAIL VARCHAR(80),
@P_WEBSITE VARCHAR(80),
@P_COMMENT VARCHAR(250),
@P_IS_PRIMARY VARCHAR(1),
@P_RETENTION VARCHAR(1),
@P_DOCUMENT_TYPE_PERSON_ID VARCHAR(2),
@P_TYPE_COMPANY VARCHAR(80),
@P_ACCOUNT_LOCAL VARCHAR(50),
@P_ACCOUNT_EXTERNAL VARCHAR(50)
AS

UPDATE CUSTOMER
   SET 
      NAME = @P_NAME,
      ADDR = @P_ADDR ,
      PHONE = @P_PHONE, 
      VAT_REGISTRATION = @P_VAT_REGISTRATION ,
      NUMBER_DOC = @P_NUMBER_DOC ,
      DISCOUNT_PERCENT = @P_DISCOUNT_PERCENT ,
      TERMS_TYPE = @P_TERMS_TYPE ,
      STATUS = @P_STATUS ,
      OPEN_DATE = @P_OPEN_DATE ,
      CONTACT = @P_CONTACT ,
      STATE_ID = @P_STATE_ID, 
      CREATE_USER = @P_CREATE_USER ,
      CREATE_DATE = @P_CREATE_DATE ,
      MODIFY_DATE = @P_MODIFY_DATE ,
      TYPE_PRICE = @P_TYPE_PRICE ,
      SALES_ID = @P_SALES_ID ,
      SELL_ZONE = @P_SELL_ZONE, 
      COUNTRY = @P_COUNTRY ,
      DEPARTMENT = @P_DEPARTMENT ,
      PROVINCE = @P_PROVINCE ,
      ADDR_DLV = @P_ADDR_DLV ,
      CURRENCY_CREDIT_LIMIT = @P_CURRENCY_CREDIT_LIMIT ,
      CREDIT_LIMIT_US = @P_CREDIT_LIMIT_US ,
      CREDIT_LIMIT = @P_CREDIT_LIMIT ,
      BALANCE = @P_BALANCE ,
      BALANCE_US = @P_BALANCE_US ,
      OBSERV = @P_OBSERV ,
      TOTAL_LETTER = @P_TOTAL_LETTER ,
      TOTAL_RECEIVABLE = @P_TOTAL_RECEIVABLE ,
      TOTAL_CHECK = @P_TOTAL_CHECK ,
      TOTAL_LETTER_PROTESTED = @P_TOTAL_LETTER_PROTESTED ,
      CUSTOMER_TYPE = @P_CUSTOMER_TYPE ,
      BUSINESS_TYPE = @P_BUSINESS_TYPE ,
      TERRITORY = @P_TERRITORY ,
      ROUTE = @P_ROUTE ,
      SEGMENT = @P_SEGMENT, 
      SEGMENT_LOCATION = @P_SEGMENT_LOCATION ,
      BANK_ID = @P_BANK_ID ,
      ACCOUNT_NO = @P_ACCOUNT_NO ,
      DATE_REVIEW = @P_DATE_REVIEW, 
      HOUR_VISIT = @P_HOUR_VISIT ,
      ATTENTION_TYPE = @P_ATTENTION_TYPE ,
      FAX_NUMBER = @P_FAX_NUMBER ,
      EMAIL = @P_EMAIL ,
      WEBSITE = @P_WEBSITE ,
      COMMENT = @P_COMMENT ,
      IS_PRIMARY = @P_IS_PRIMARY ,
      RETENTION = @P_RETENTION ,
      DOCUMENT_TYPE_PERSON_ID = @P_DOCUMENT_TYPE_PERSON_ID ,
      TYPE_COMPANY = @P_TYPE_COMPANY ,
      ACCOUNT_LOCAL = @P_ACCOUNT_LOCAL, 
      ACCOUNT_EXTERNAL = @P_ACCOUNT_EXTERNAL 
 WHERE ID = @P_ID