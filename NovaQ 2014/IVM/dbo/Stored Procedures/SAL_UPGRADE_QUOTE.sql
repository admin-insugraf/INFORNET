CREATE PROC [dbo].[SAL_UPGRADE_QUOTE]
--DECLARE
@NUMERO VARCHAR(7),
@USER VARCHAR(8),
@MONTO VARCHAR(15),
@MONTOIGV VARCHAR(15),
@IDE VARCHAR(30),
@EXPIRES_DATE VARCHAR(10),
@PLACE_SHIPPER VARCHAR(80),
@TIME_SHIPPER VARCHAR(80)
AS
SET NOCOUNT ON
/*SET @NUMERO='0000015'
SET @USER='1'
SET @MONTO='1000'
SET @MONTOIGV='190'
SET @IDE='DEVELOPER6'
SET @EXPIRES_DATE='rr'
