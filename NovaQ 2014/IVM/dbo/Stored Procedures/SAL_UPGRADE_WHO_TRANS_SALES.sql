CREATE PROC [dbo].[SAL_UPGRADE_WHO_TRANS_SALES]    
--DECLARE    
@TD VARCHAR(2),@ALMA VARCHAR(2),@NUMERO VARCHAR(10),@FECHA VARCHAR(10),@TIPO_CAMBIO VARCHAR(15),@TD_REF VARCHAR(2),    
@NUM_REF VARCHAR(10),@USER VARCHAR(10),@COD_CLI VARCHAR(11),@RUC VARCHAR(11),@NOM_CLI VARCHAR(100),@PAGO VARCHAR(2),    
@MONEDA VARCHAR(2),@MONTO VARCHAR(15),@HORA VARCHAR(20),@ORDENCOMPRA VARCHAR(20),@COTIZACION VARCHAR(7),    
@PEDIDO VARCHAR(7),@GLOSA VARCHAR(80),@IDE VARCHAR(50),@FLAG_REF VARCHAR(1),@ANOMES VARCHAR(6), @CANT_ERROR INT OUTPUT    
AS    
/*SET @TD='FT'    
