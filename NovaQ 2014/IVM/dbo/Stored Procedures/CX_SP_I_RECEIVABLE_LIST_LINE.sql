  
CREATE PROC CX_SP_I_RECEIVABLE_LIST_LINE  
@P_ID VARCHAR(6),  
@P_ITEM VARCHAR(3),  
@P_TYPE_DOC VARCHAR(2),  
@P_NUMBER_DOC VARCHAR(20),  
@P_TYPE_OPERATION VARCHAR(1),  
@P_REC_ID VARCHAR(2),  
@P_DATE SMALLDATETIME,  
@P_AMOUNT FLOAT,  
@P_CURRENCY_ID VARCHAR(2),  
@P_SELL_RATE FLOAT,  
@P_CREATE_DATE SMALLDATETIME,  
@P_USER_ID VARCHAR(100),  
@P_COMMENT VARCHAR(30),  
@P_SALES_ID VARCHAR(2),  
@P_BANK_ID VARCHAR(3),  
@P_BANK_DESCRIPTION VARCHAR(100),  
@P_DOC_REF VARCHAR(2),  
@P_NUM_REF VARCHAR(21),  
@P_IS_CASH_BANK INT,  
@P_AMOUNT_PER FLOAT,  
@P_BANK_BUSSINESS_ID VARCHAR(30),  
@P_ACCOUNT_BANK_CHECK VARCHAR(20),  
@P_PAY_AUTO VARCHAR(1),  
@P_ANNEX_ID_AUX VARCHAR(50),  
@P_DOCUMET_ID VARCHAR(2),  
@P_NUMBER_SERIE VARCHAR(5),  
@P_NUMBER_DOCUMENT VARCHAR(20),  
@P_MEDIOS_PAGO VARCHAR(20)  
AS  
  
INSERT INTO RECEIVABLE_LIST_LINE(ID,ITEM,TYPE_DOC,NUMBER_DOC,TYPE_OPERATION,REC_ID,DATE,AMOUNT,CURRENCY_ID,SELL_RATE,  
CREATE_DATE,USER_ID,COMMENT,SALES_ID,BANK_ID,BANK_DESCRIPTION,DOC_REF,NUM_REF,IS_CASH_BANK,AMOUNT_PER,BANK_BUSSINESS_ID,  
ACCOUNT_BANK_CHECK,PAY_AUTO,ANNEX_ID_AUX,DOCUMET_ID,NUMBER_SERIE,NUMBER_DOCUMENT,MEDIOS_PAGO)  
VALUES(@P_ID ,  
@P_ITEM ,  
@P_TYPE_DOC ,  
@P_NUMBER_DOC ,  
@P_TYPE_OPERATION ,  
@P_REC_ID ,  
@P_DATE ,  
@P_AMOUNT ,  
@P_CURRENCY_ID ,  
@P_SELL_RATE ,  
@P_CREATE_DATE ,  
@P_USER_ID ,  
@P_COMMENT ,  
@P_SALES_ID ,  
@P_BANK_ID ,  
@P_BANK_DESCRIPTION ,  
@P_DOC_REF ,  
@P_NUM_REF ,    
@P_IS_CASH_BANK ,  
@P_AMOUNT_PER ,  
@P_BANK_BUSSINESS_ID ,  
@P_ACCOUNT_BANK_CHECK ,  
@P_PAY_AUTO ,  
@P_ANNEX_ID_AUX ,  
@P_DOCUMET_ID ,  
@P_NUMBER_SERIE ,  
@P_NUMBER_DOCUMENT ,  
@P_MEDIOS_PAGO)