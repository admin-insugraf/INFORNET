


CREATE PROC CX_SP_S_CUSTOMER_XID
@P_ID VARCHAR(11) = '20419016242'
AS

SELECT 
ID,
NAME,
ADDR,
PHONE,
VAT_REGISTRATION,
NUMBER_DOC,
DISCOUNT_PERCENT,
TERMS_TYPE,
STATUS,
OPEN_DATE,
CONTACT,
STATE_ID,
CREATE_USER,
CREATE_DATE,
MODIFY_DATE,
TYPE_PRICE,
SALES_ID,
SELL_ZONE,
COUNTRY,
DEPARTMENT,
PROVINCE,
ADDR_DLV,
CURRENCY_CREDIT_LIMIT,
CREDIT_LIMIT_US,
CREDIT_LIMIT,
BALANCE,
BALANCE_US,
OBSERV,
isnull(TOTAL_LETTER,0)as 'TOTAL_LETTER',
isnull(TOTAL_RECEIVABLE,0) as 'TOTAL_RECEIVABLE',
isnull(TOTAL_CHECK,0)as 'TOTAL_CHECK',
isnull(TOTAL_LETTER_PROTESTED,0) as 'TOTAL_LETTER_PROTESTED',
isnull(CUSTOMER_TYPE,'') as 'CUSTOMER_TYPE',
BUSINESS_TYPE,
TERRITORY,
ROUTE,
SEGMENT,
SEGMENT_LOCATION,
BANK_ID,
ACCOUNT_NO,
DATE_REVIEW,
HOUR_VISIT,
ATTENTION_TYPE,
FAX_NUMBER,
EMAIL,
WEBSITE,
COMMENT,
IS_PRIMARY,
RETENTION,
DOCUMENT_TYPE_PERSON_ID,
TYPE_COMPANY,
ACCOUNT_LOCAL,
ACCOUNT_EXTERNAL
FROM CUSTOMER
WHERE ID = @P_ID