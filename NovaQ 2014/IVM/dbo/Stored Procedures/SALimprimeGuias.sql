NUMBER_ESTIMATING, DISCOUNT_PER_CUST, DISCOUNT_PER_SP, C.AMOUNT, CARRIER_NAME, CARRIER_ADDR, CARRIER_VAT, C.NUMBER_REGISTRATION, NUMBER_IMPORT, NUMBER_LIQ, PRINTER_STATUS, STATUS_CLOSE, TYPE_SHIPPER, ZONE_FREIGHT, IS_GUIA, IS_POST, FREIGHT, 
ORDER_REF, COST, RECEP_NAME, DOCUMENT_RECEP, NUM_ORDER_MANUFACT, INTERFACE, C.ACCOUNT 

,ITEM, PART_ID, REF_ID, QTY, QTY_DLV, QTY_REF, QTY_INVOICED, NUM_ORDER, D.UNIT_PRICE, AVERAGE_COST, AMOUNT_SALES, D.DISCOUNT, STOCK, AMOUNT_TAX, D.AMOUNT, AMOUNT_US, NUMBER_SERIE, STATUS_DOC, DATE_DOC, D.CCOST_ID, D.WAREHOUSE_REF, TEXT_COMMENT, 
D.STATUS, D.TRANS_ID, VAL_AMOUNT, NUM_VOUCHER, D.CURRENCY_ID AS CURRENCY_LINE, TYPE, TYPE_EXCHANGE, PRICE_SALES, TOTAL_SALES, D.DATE_CADUCATE AS DATE_CADUCATE_LINE, RETURN_AMOUNT, AUTHORIZED, PART_DESCRIPTION, 
D.DISCOUNT_PERCENT AS DISCOUNT_PERCENT_LINE, TAX_PERCENT, DISCOUNT_CUST, DISCOUNT_SP, NUMBER_INVOICE, NUMBER_LOT, UNIT_PART, ORDER_MANUFACT_ID, EQUIP_ID, FREIGTH, ITEMI, QTY_BRUTE, DISCOUNT_PER_QTY, STATUS_VALUE, UNIT_REFERENCE, QTY_REFERENCE, 
D.COMMENT AS COMMENT_LINE, D.REFERENCE AS REFERENCE_LINE, D.ACCOUNT AS ACCOUNT_LINE 

,M.ID AS COD_CUSTOMER, M.NAME, M.ADDR, M.PHONE, M.VAT_REGISTRATION AS VAT_REG_CUSTOMER, NUMBER_DOC, M.DISCOUNT_PERCENT AS DISCOUNT_PERCENT_CUSTOMER, TERMS_TYPE, M.STATUS AS STATUS_CUSTOMER, OPEN_DATE, CONTACT, STATE_ID, M.CREATE_USER, 
M.CREATE_DATE, MODIFY_DATE, TYPE_PRICE, M.SALES_ID AS SALES_ID_CUSTOMER, SELL_ZONE, COUNTRY, DEPARTMENT, PROVINCE, M.ADDR_DLV AS ADDR_DLV_CUSTOMER, CURRENCY_CREDIT_LIMIT, CREDIT_LIMIT_US, CREDIT_LIMIT, BALANCE, BALANCE_US, OBSERV, TOTAL_LETTER, 
TOTAL_RECEIVABLE, TOTAL_CHECK, TOTAL_LETTER_PROTESTED, CUSTOMER_TYPE, BUSINESS_TYPE, TERRITORY, ROUTE, SEGMENT, SEGMENT_LOCATION, BANK_ID, ACCOUNT_NO, DATE_REVIEW, HOUR_VISIT, ATTENTION_TYPE, FAX_NUMBER, EMAIL, WEBSITE, 
M.COMMENT AS COMMENT_CUSTOMER, IS_PRIMARY, RETENTION,

A.ID AS COD_PART, ID_FAB, DESCRIPTION, DESCRIPTION_OPT, FAMILY, MODEL, UNIT_OF_MEASUREMENT, GROUP_ID, A.ACCOUNT AS ACCOUNT_PART, SERIES, A.UNIT_PRICE AS UNIT_PRICE_PART, A.DISCOUNT AS DISCOUNT_PART, PRICE_BUY, VENDOR_ID_PART, 
