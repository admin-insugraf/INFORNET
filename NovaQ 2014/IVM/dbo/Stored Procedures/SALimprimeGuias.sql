DECLARE @STRquery nvarchar(4000)
DECLARE @TIPO CHAR(2)
SET @TIPO='GS'
set @STRquery='SELECT C.WAREHOUSE_ID, C.DOCUMENT_ID, C.NUMBER_DOCUMENT, DATE_DOCUMENT, TYPE_TRANS, C.TRANS_ID, DOCUMENT_STATUS, DOC_ID_REF, NUM_ID_REF, AUTORIZED_ID, DATE_RETURN, VENDOR_ID, C.CCOST_ID, C.WAREHOUSE_REF, C.COMMENT, UPDATE_DATE, HOUR, 
