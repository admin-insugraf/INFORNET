,T.ID AS COD_TERM, T.NAME AS NAME_TERM, NET_DAYS, REGISTER_DATE, EFFECTIVE_DATE

FROM WAREHOUSE_TRANS C INNER JOIN WAREHOUSE_TRANS_LINE D ON C.WAREHOUSE_ID=D.WAREHOUSE_ID AND C.DOCUMENT_ID=D.DOCUMENT_ID AND C.NUMBER_DOCUMENT=D.NUMBER_DOCUMENT 
INNER JOIN CUSTOMER M ON C.CUSTOMER_ID=M.ID INNER JOIN PART A ON D.PART_ID = A.ID LEFT JOIN CARRIER R ON C.CARRIER_ID=R.ID LEFT JOIN TERMS T ON C.SALES_TERM=T.ID 
WHERE C.WAREHOUSE_ID=@ALMACEN AND C.DOCUMENT_ID=@TIPO AND C.NUMBER_DOCUMENT=@NUMERO'
--PRINT(@STRquery)

exec sp_executesql @STRquery,N'@ALMACEN NVARCHAR(2),@NUMERO NVARCHAR(10),@TIPO CHAR(2)',@ALMACEN,@NUMERO,@TIPO





