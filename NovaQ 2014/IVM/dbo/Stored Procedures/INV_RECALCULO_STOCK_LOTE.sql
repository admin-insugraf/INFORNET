CREATE procedure [dbo].[INV_RECALCULO_STOCK_LOTE]  
--DECLARE  
@alma AS VARCHAR(500),@mesPOST AS VARCHAR(2),@anoPOST AS VARCHAR(4)  
  
/*SET @alma='"01","02"'  
SET @mesPOST='05'  
SET @anoPOST='2007'  
--*/AS  
  
SET NOCOUNT ON  
DECLARE @Arti AS VARCHAR(20)  
DECLARE @Ing AS numeric(15,6)  
DECLARE @Sal AS numeric(15,6)  
DECLARE @LOT AS VARCHAR(20)  
DECLARE @TOTSTK AS VARCHAR(30)  
DECLARE @ALMACEN AS VARCHAR(500)  

EXEC('set quoted_identifier off update S set S.QTY_ON_HAND=0 from WAREHOUSE_TRANS A INNER JOIN WAREHOUSE_TRANS_LINE B ON   
 A.WAREHOUSE_ID = B.WAREHOUSE_ID AND A.DOCUMENT_ID = B.DOCUMENT_ID AND A.NUMBER_DOCUMENT = B.NUMBER_DOCUMENT INNER JOIN PART C ON B.PART_ID = C.ID 
 inner join PART_QTY S ON S.PART_ID=B.PART_ID AND S.WAREHOUSE_ID=B.WAREHOUSE_ID
where B.WAREHOUSE_ID in('+@alma+') AND A.STATUS_GUIA<>"A" AND NOT (A.DOCUMENT_ID="GS" AND A.TRANS_ID="GF" AND A.STATUS_GUIA="F")   
 AND NOT (C.IS_STOCKED="N" AND C.SERIES="N" AND C.IS_LOT="N")AND (B.PART_ID<>"TEXTO")AND C.IS_LOT="S"  
 and A.DATE_DOCUMENT<"01/"+"'+@mesPOST+'"+"/"+"'+@anoPOST+'"')  

exec('set quoted_identifier off update S set S.QTY_ON_HAND=0 from WAREHOUSE_TRANS A INNER JOIN WAREHOUSE_TRANS_LINE B ON   
 A.WAREHOUSE_ID = B.WAREHOUSE_ID AND A.DOCUMENT_ID = B.DOCUMENT_ID AND A.NUMBER_DOCUMENT = B.NUMBER_DOCUMENT INNER JOIN PART C ON B.PART_ID = C.ID 
 inner join PART_QTY S ON S.PART_ID=B.PART_ID AND S.WAREHOUSE_ID=B.WAREHOUSE_ID
where B.WAREHOUSE_ID in('+@alma+') AND A.STATUS_GUIA<>"A" AND NOT (A.DOCUMENT_ID="GS" AND A.TRANS_ID="GF" AND A.STATUS_GUIA="F")   
 AND NOT (C.IS_STOCKED="N" AND C.SERIES="N" AND C.IS_LOT="N")AND (B.PART_ID<>"TEXTO")AND C.IS_LOT="S"  
 and A.DATE_DOCUMENT<"01/"+"'+@mesPOST+'"+"/"+"'+@anoPOST+'"')  


 /*exec('set quoted_identifier off DECLARE RECALC_STOCK_L CURSOR FOR  
 SELECT B.PART_ID,B.WAREHOUSE_ID,B.NUMBER_LOT,SUM(CASE WHEN A.TYPE_TRANS="I" THEN B.QTY ELSE 0 END)AS INGRESO,  
 SUM(CASE WHEN A.TYPE_TRANS="S" THEN B.QTY ELSE 0 END)as SALIDA  
 from WAREHOUSE_TRANS A INNER JOIN WAREHOUSE_TRANS_LINE B ON   
