--DECLARE
@COD_CLI VARCHAR(11),@TIPO VARCHAR(2),@NUM_DOC VARCHAR(10),@FECHA VARCHAR(10),@FECHA_VEN VARCHAR(10),
@TD_REF VARCHAR(2),@NUM_REF VARCHAR(10),@VENDEDOR VARCHAR(2),@MONTO VARCHAR(15),@SALDO VARCHAR(15),
@SALDO_INI VARCHAR(15),@MONEDA VARCHAR(2),@TIPO_CAMBIO VARCHAR(15),@DH VARCHAR(1),@USER VARCHAR(8),
@TIPO_FAC VARCHAR(2),@PAGO VARCHAR(2),@PTOVTA VARCHAR(2),@CANT_ERROR INT OUTPUT
AS
SET NOCOUNT ON

/*SET @COD_CLI='01'
