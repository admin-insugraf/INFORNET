--DECLARE
@NUMERO AS VARCHAR(13)
/*
SET @NUMERO='IMP123'
*/
AS
declare @STRquery nvarchar(4000)
set @STRquery='SELECT  I.ID AS I_ID, I.VENDOR_ID AS I_VENDOR_ID, I.DOCUMENT_DATE AS I_DOCUMENT_DATE, 
I.PROMISE_DATE AS I_PROMISE_DATE,I.AMOUNT AS I_AMOUNT, I.CURRENCY_ID_IMP AS CURRENCY_ID_IMP, 
I.EQUIVALENCE_US AS I_EQUIVALENCE_US,I.CURRENCY_EXCHANGE AS I_CURRENCY_EXCHANGE,I.SOLIINSP AS I_SOLIINSP,
I.GUIATRAN AS I_GUIATRAN, I.AMOUNT_LIQ AS I_AMOUNT_LIQ,I.LLIQREAL AS I_LLIQREAL, I.AMOUNT_BALANCE AS I_AMOUNT_BALANCE,
I.AMOUNT_BALANCE_LIQ AS I_AMOUNT_BALANCE_LIQ,I.COMMENT AS I_COMMENT, I.LREAL AS I_LREAL,I.TYPE_ORDER AS I_TYPE_ORDER,
I.NUMBER_LIQ AS I_NUMBER_LIQ,I.NADVALOR AS I_NADVALOR, I.ITINERANT AS I_ITINERANT, I.CPACKING AS I_CPACKING,
I.CURR_EXCHANGE_TYPE AS I_CURR_EXCHANGE_TYPE,I.TIPPREIMP AS I_TIPPREIMP, I.STATUS_ID AS I_STATUS_ID, I.AMOUNT_FLETE AS I_AMOUNT_FLETE, 
I.NUMBER_IMPORT_INT AS I_NUMBER_IMPORT_INT, I.SECURE AS I_SECURE,T.BILL_NAME_COMPANY AS T_BILL_NAME_COMPANY, 
T.BILL_ADDRESS_COMPANY AS T_BILL_ADDRESS_COMPANY, T.BILL_TELFAX AS T_BILL_TELFAX, T.BILL_CONTAC AS T_BILL_CONTAC, 
T.BILL_FAX AS T_BILL_FAX,T.EMBARQUE AS T_EMBARQUE,T.TERMS_TYPE AS T_TERMS_TYPE, T.NAME_FACT AS NAME_FACT, T.ADJUNTAR AS T_ADJUNTAR, 
T.IMPORTANT AS T_IMPORTANT,T.DOCUMENTS AS T_DOCUMENTS,T.COMMENT AS T_COMMENT, T.COMMENT_TECNIC AS T_COMMENT_TECNIC, 
V.NAME AS V_NAME, V.VAT_REGISTRATION AS V_VAT_REGISTRATION, V.ADDR AS V_ADDR, V.STATE_ID AS V_STATE_ID,  
V.PHONE AS V_PHONE,V.FAX_NUMBER AS V_FAX_NUMBER,V.EMAIL AS V_EMAIL, V.WEBSITE AS V_WEBSITE,V.CONTACT V_CONTACT, 
V.CONTACT_POSITION AS V_CONTACT_POSITION, V.CONTACT_PHONE AS V_CONTACT_PHONE, V.CONTACT_EMAIL AS V_CONTACT_EMAIL,V.REPRESENT AS V_REPRESENT, 
V.REPRESENT_POSITION AS V_REPRESENT_POSITION, V.REPRESENT_PHONE AS V_REPRESENT_PHONE,V.REPRESENT_EMAIL AS V_REPRESENT_EMAIL,V.COMMENT AS V_COMMENT, 
