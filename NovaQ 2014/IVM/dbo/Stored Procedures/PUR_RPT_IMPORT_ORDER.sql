I.ID = D.ID INNER JOIN PART P ON D.PART_ID = P.ID INNER JOIN VENDOR V 
ON I.VENDOR_ID = V.ID INNER JOIN DATA_IMPORT T ON 
I.ID = T.ID  WHERE I.ID=@NUMERO  ORDER BY D.ITEM' 
exec sp_executesql @STRquery,N'@NUMERO varchar(13)',@NUMERO
