   FROM CO_TB_ASIENTO_CAB A INNER JOIN CO_TB_ASIENTO_DET B ON A.AC_ID = B.AD_IDCAB    
   WHERE  AC_ANHO = @P_AYO and ac_mes <= @P_MES  AND LEFT(AD_CUENTA,2) IN (    
   SELECT CC_CUENTA FROM CO_TB_CTA_CONCEPTO_EGP WHERE   CC_CONCEPTO = 14)    
   )  
 end  
  
   UPDATE CO_TB_REP_EGP SET  EGP_VALOR2 = @OTROS_GASTOS WHERE EGP_IDCONCEPTO_EGP = 14 
    
 if @P_ES_MENSUAL = 1 begin           
  SET @INGRESOS_EXATRAORDINARIOS =    
  (    
  SELECT ISNULL(ABS(SUM(AD_DEBE)-SUM(AD_HABER)) ,0)    
