  (    
  SELECT ISNULL(ABS(SUM(AD_DEBE)-SUM(AD_HABER)) ,0)    
  FROM CO_TB_ASIENTO_CAB A INNER JOIN CO_TB_ASIENTO_DET B ON A.AC_ID = B.AD_IDCAB    
  WHERE  AC_ANHO = @P_AYO and ac_mes = @P_MES  AND LEFT(AD_CUENTA,2) IN (    
